#' Create an IHE AIW-I (AI Workflow for Imaging) UPS-RS Workitem
#'
#' Initializes a workitem in the `"SCHEDULED"` state following the IHE AIW-I
#' Unified Procedure Step (UPS-RS) state machine.
#'
#' @param workitem_id Unique workitem identifier string.
#' @param study_uid StudyInstanceUID string.
#' @param model_name AI model identifier string.
#' @param input_series_uid Optional SeriesInstanceUID string.
#'
#' @return An S3 `"dicom_ihe_workitem"` object.
#' @examples
#' wi <- ihe_aiw_workitem("wi-001", study_uid = "1.2.3.4", model_name = "TotalSegmentator")
#' wi$state
#' @export
ihe_aiw_workitem <- function(workitem_id,
                             study_uid,
                             model_name,
                             input_series_uid = NULL) {
  srv_check_scalar_chr(workitem_id, "workitem_id")
  srv_check_scalar_chr(study_uid, "study_uid")
  srv_check_scalar_chr(model_name, "model_name")
  structure(
    list(
      workitem_id = workitem_id,
      study_uid = study_uid,
      model_name = model_name,
      input_series_uid = input_series_uid %||% NA_character_,
      state = "SCHEDULED",
      performer = NA_character_,
      output_refs = list(),
      updated_at = format(Sys.time(), "%Y-%m-%dT%H:%M:%SZ", tz = "UTC")
    ),
    class = "dicom_ihe_workitem"
  )
}

#' Transition an IHE AIW-I Workitem State
#'
#' Enforces valid UPS-RS state transitions:
#' `"SCHEDULED"` -> `"IN PROGRESS"` or `"CANCELED"`;
#' `"IN PROGRESS"` -> `"COMPLETED"` or `"CANCELED"`.
#'
#' @param workitem A `"dicom_ihe_workitem"` from [ihe_aiw_workitem()].
#' @param to_state Target state: `"IN PROGRESS"`, `"COMPLETED"`, or `"CANCELED"`.
#' @param performer Optional AI worker/performer identifier.
#' @param output_refs Optional named list of generated DICOM SOP UIDs.
#'
#' @return Updated `"dicom_ihe_workitem"` object.
#' @export
ihe_aiw_transition <- function(workitem,
                               to_state = c("IN PROGRESS", "COMPLETED", "CANCELED"),
                               performer = NULL,
                               output_refs = list()) {
  if (!inherits(workitem, "dicom_ihe_workitem")) {
    cli::cli_abort("{.arg workitem} must be a {.cls dicom_ihe_workitem} object.")
  }
  to_state <- match.arg(to_state)
  allowed <- switch(
    workitem$state,
    "SCHEDULED" = c("IN PROGRESS", "CANCELED"),
    "IN PROGRESS" = c("COMPLETED", "CANCELED"),
    character(0)
  )
  if (!(to_state %in% allowed)) {
    cli::cli_abort("Invalid IHE AIW-I transition from {.val {workitem$state}} to {.val {to_state}}.")
  }
  workitem$state <- to_state
  if (!is.null(performer)) workitem$performer <- as.character(performer)
  if (length(output_refs) > 0L) workitem$output_refs <- output_refs
  workitem$updated_at <- format(Sys.time(), "%Y-%m-%dT%H:%M:%SZ", tz = "UTC")
  workitem
}

#' Construct and Validate an IHE AIR (AI Results) Conformance Bundle
#'
#' Packages a generated DICOM AI artifact (`SEG` or `SR_TID1500`) alongside a
#' FHIR `DiagnosticReport` and W3C/FHIR `Provenance` record with model version
#' and uncertainty metadata.
#'
#' @param study_uid StudyInstanceUID string.
#' @param model_name AI model name.
#' @param model_version AI model semantic version string.
#' @param dicom_artifact_type Either `"SEG"` or `"SR_TID1500"`.
#' @param dicom_sop_uid SOPInstanceUID of the generated DICOM AI object.
#' @param fhir_report Named list of FHIR `DiagnosticReport` fields.
#' @param uncertainty_summary Named list of model uncertainty metrics.
#'
#' @return An S3 `"dicom_ihe_air_bundle"` object.
#' @examples
#' air <- ihe_air_bundle(
#'   study_uid = "1.2.3.4",
#'   model_name = "TotalSegmentator",
#'   model_version = "2.4.0",
#'   dicom_artifact_type = "SEG",
#'   dicom_sop_uid = "1.2.3.99"
#' )
#' air$provenance$resourceType
#' @export
ihe_air_bundle <- function(study_uid,
                           model_name,
                           model_version,
                           dicom_artifact_type = c("SEG", "SR_TID1500"),
                           dicom_sop_uid,
                           fhir_report = list(),
                           uncertainty_summary = list()) {
  srv_check_scalar_chr(study_uid, "study_uid")
  srv_check_scalar_chr(model_name, "model_name")
  srv_check_scalar_chr(model_version, "model_version")
  srv_check_scalar_chr(dicom_sop_uid, "dicom_sop_uid")
  dicom_artifact_type <- match.arg(dicom_artifact_type)

  now_iso <- format(Sys.time(), "%Y-%m-%dT%H:%M:%SZ", tz = "UTC")
  diag_report <- utils::modifyList(
    list(
      resourceType = "DiagnosticReport",
      status = "preliminary",
      code = list(text = paste("AI", dicom_artifact_type, "Analysis")),
      conclusion = paste("Generated by", model_name, model_version)
    ),
    fhir_report
  )
  prov <- list(
    resourceType = "Provenance",
    recorded = now_iso,
    agent = list(list(
      who = list(display = paste0(model_name, " v", model_version))
    )),
    entity = list(list(
      role = "source",
      what = list(identifier = list(value = study_uid))
    ))
  )

  structure(
    list(
      study_uid = study_uid,
      model_name = model_name,
      model_version = model_version,
      dicom_artifact_type = dicom_artifact_type,
      dicom_sop_uid = dicom_sop_uid,
      uncertainty_summary = uncertainty_summary,
      diagnostic_report = diag_report,
      provenance = prov
    ),
    class = "dicom_ihe_air_bundle"
  )
}
